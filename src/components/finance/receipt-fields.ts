import { currencyFmt } from '@/lib/helpers';
import {
  DEFAULT_RECEIPT_DOCUMENT,
  DEFAULT_RECEIPT_FIELD_LABELS,
  getIntlLocale,
  RECEIPT_FIELD_KEYS,
  type NamespaceTranslate,
  type ReceiptFieldKey,
} from './operations-i18n';

export type { ReceiptFieldKey };

export interface ReceiptData {
  receiptType: 'transaction' | 'purchase';
  receiptNumber: string;
  issuedAt: string;
  data: {
    id: string;
    type?: string;
    rawType?: string;
    description?: string;
    merchant?: string;
    amount?: string;
    totalAmount?: string;
    amountRaw?: number;
    totalAmountRaw?: number;
    date: string;
    category: string;
    categoryColor: string;
    account?: string;
    accountColor?: string;
    card: string | null;
    cardBrand?: string | null;
    installment?: string | null;
    notes: string | null;
    items?: Array<{
      name: string;
      quantity: number;
      unitPrice: string;
      totalPrice: string;
      totalPriceRaw: number;
    }>;
    itemsCount?: number;
  };
}

export interface BuildReceiptFieldsOptions {
  locale?: string;
  labels?: Partial<Record<ReceiptFieldKey, string>>;
  unavailableAmount?: string;
}

function field(
  key: ReceiptFieldKey,
  value: string | undefined,
  labels: Partial<Record<ReceiptFieldKey, string>>,
) {
  return { key, label: labels[key] ?? DEFAULT_RECEIPT_FIELD_LABELS[key], value };
}

export function buildReceiptFields(receipt: ReceiptData, options?: BuildReceiptFieldsOptions) {
  const d = receipt.data;
  const isPurchase = receipt.receiptType === 'purchase';
  const rawTotal = isPurchase ? d.totalAmountRaw : d.amountRaw;
  const locale = options?.locale;
  const resolvedLabels = options?.labels ?? DEFAULT_RECEIPT_FIELD_LABELS;
  const unavailableAmount = options?.unavailableAmount ?? DEFAULT_RECEIPT_DOCUMENT.unavailableAmount;
  const rows = isPurchase
    ? [field('merchant', d.merchant, resolvedLabels), field('category', d.category, resolvedLabels),
        ...(d.card ? [field('card', d.card, resolvedLabels)] : []),
        ...(d.installment ? [field('installment', d.installment, resolvedLabels)] : []),
        field('date', d.date, resolvedLabels)]
    : [field('description', d.description, resolvedLabels), field('type', d.type, resolvedLabels), field('category', d.category, resolvedLabels),
        ...(d.account ? [field('account', d.account, resolvedLabels)] : []),
        ...(d.card ? [field('card', d.card, resolvedLabels)] : []),
        field('date', d.date, resolvedLabels)];

  return {
    receiptType: receipt.receiptType,
    receiptNumber: receipt.receiptNumber,
    issuedDate: new Date(receipt.issuedAt).toLocaleString(getIntlLocale(locale), {
      day: '2-digit', month: '2-digit', year: 'numeric', hour: '2-digit', minute: '2-digit',
    }),
    rows,
    categoryColor: d.categoryColor,
    items: isPurchase && d.items?.length ? {
      count: d.itemsCount,
      entries: d.items.map((item) => ({
        name: item.name,
        units: `${item.quantity}x ${item.unitPrice}`,
        total: {
          display: typeof item.totalPriceRaw === 'number' && Number.isFinite(item.totalPriceRaw)
            ? currencyFmt(item.totalPriceRaw, locale)
            : unavailableAmount,
          text: item.totalPrice,
        },
      })),
    } : null,
    notes: d.notes,
    // A prévia e a impressão validam o número. O TXT conserva o valor formatado pela API.
    total: {
      display: typeof rawTotal === 'number' && Number.isFinite(rawTotal) ? currencyFmt(rawTotal, locale) : unavailableAmount,
      text: isPurchase ? d.totalAmount : d.amount,
    },
  };
}

export type ReceiptFields = ReturnType<typeof buildReceiptFields>;

export interface ReceiptPrintTexts {
  brandName: string;
  brandSubtitle: string;
  printWindowTitle: string;
  receiptHeading: string;
  itemsHeading: (count: number) => string;
  notes: string;
  totalUpper: string;
  thankYou: string;
  autoGeneratedPrint: string;
}

export interface BuildReceiptPrintOptions extends BuildReceiptFieldsOptions {
  texts?: Partial<ReceiptPrintTexts>;
}

/** Resolves all receipt row labels from a namespace translator. */
export function resolveReceiptFieldLabels(t: NamespaceTranslate): Record<ReceiptFieldKey, string> {
  return Object.fromEntries(
    RECEIPT_FIELD_KEYS.map((key) => [key, t(`fields.${key}`)]),
  ) as Record<ReceiptFieldKey, string>;
}

function escapeHtml(value: string): string {
  return value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

/** Builds standalone printable HTML for a transaction or purchase receipt. */
export function buildReceiptPrintHtml(receipt: ReceiptData, options?: BuildReceiptPrintOptions): string {
  const { rows, items, notes, receiptNumber, issuedDate, total } = buildReceiptFields(receipt, options);
  const lang = getIntlLocale(options?.locale);
  const texts: ReceiptPrintTexts = {
    brandName: options?.texts?.brandName ?? DEFAULT_RECEIPT_DOCUMENT.brandName,
    brandSubtitle: options?.texts?.brandSubtitle ?? DEFAULT_RECEIPT_DOCUMENT.brandSubtitle,
    printWindowTitle: options?.texts?.printWindowTitle ?? DEFAULT_RECEIPT_DOCUMENT.printWindowTitle,
    receiptHeading: options?.texts?.receiptHeading ?? DEFAULT_RECEIPT_DOCUMENT.receiptHeading,
    itemsHeading: options?.texts?.itemsHeading ?? ((count: number) => `Itens (${count})`),
    notes: options?.texts?.notes ?? DEFAULT_RECEIPT_DOCUMENT.notes,
    totalUpper: options?.texts?.totalUpper ?? DEFAULT_RECEIPT_DOCUMENT.totalUpper,
    thankYou: options?.texts?.thankYou ?? DEFAULT_RECEIPT_DOCUMENT.thankYou,
    autoGeneratedPrint: options?.texts?.autoGeneratedPrint ?? DEFAULT_RECEIPT_DOCUMENT.autoGeneratedPrint,
  };
  const rowsHtml = rows
    .map(({ label, value }) => `<div class="receipt-row"><span class="receipt-label">${escapeHtml(label)}</span><span class="receipt-value">${escapeHtml(value ?? '—')}</span></div>`)
    .join('');

  const itemsHtml = items
    ? `<div class="receipt-divider"></div>
       <p class="receipt-section-title">${escapeHtml(texts.itemsHeading(items.count ?? items.entries.length))}</p>
       ${items.entries
         .map(
           (item) => `<div class="receipt-row">
             <span class="receipt-label">${escapeHtml(item.name)} (${escapeHtml(item.units)})</span>
             <span class="receipt-value">${escapeHtml(item.total.display)}</span>
           </div>`,
         )
         .join('')}`
    : '';

  const notesHtml = notes
    ? `<div class="receipt-divider"></div>
       <p class="receipt-label">${escapeHtml(texts.notes)}</p>
       <p class="receipt-notes">${escapeHtml(notes)}</p>`
    : '';

  return `<!DOCTYPE html>
<html lang="${escapeHtml(lang)}">
  <head>
    <meta charset="utf-8" />
    <title>${escapeHtml(texts.printWindowTitle)}</title>
    <style>
      * { margin: 0; padding: 0; box-sizing: border-box; }
      body {
        font-family: ui-monospace, SFMono-Regular, Menlo, Monaco, Consolas, monospace;
        padding: 32px;
        max-width: 420px;
        margin: 0 auto;
        color: #111111;
        background: #ffffff;
        line-height: 1.5;
        font-size: 13px;
      }
      .receipt-header { text-align: center; margin-bottom: 16px; }
      .receipt-brand { font-size: 16px; font-weight: 700; }
      .receipt-subtitle, .receipt-meta { font-size: 12px; color: #555555; }
      .receipt-title { font-size: 15px; font-weight: 700; margin-top: 10px; letter-spacing: 0.06em; }
      .receipt-divider { border-top: 1px solid #d4d4d8; margin: 12px 0; }
      .receipt-section-title { font-size: 12px; font-weight: 700; text-transform: uppercase; color: #555555; margin-bottom: 6px; }
      .receipt-row { display: flex; justify-content: space-between; gap: 12px; padding: 3px 0; }
      .receipt-label { color: #555555; }
      .receipt-value { font-weight: 600; text-align: right; }
      .receipt-notes { font-size: 12px; font-style: italic; margin-top: 4px; }
      .receipt-total { display: flex; justify-content: space-between; align-items: baseline; font-size: 15px; font-weight: 700; padding: 4px 0; }
      .receipt-footer { text-align: center; font-size: 12px; color: #555555; margin-top: 8px; }
      @media print {
        body { padding: 16px; }
      }
    </style>
  </head>
  <body>
    <div class="receipt-header">
      <p class="receipt-brand">${escapeHtml(texts.brandName)}</p>
      <p class="receipt-subtitle">${escapeHtml(texts.brandSubtitle)}</p>
      <p class="receipt-title">${escapeHtml(texts.receiptHeading)}</p>
      <p class="receipt-meta">${escapeHtml(receiptNumber)} · ${escapeHtml(issuedDate)}</p>
    </div>
    <div class="receipt-divider"></div>
    ${rowsHtml}
    ${itemsHtml}
    ${notesHtml}
    <div class="receipt-divider"></div>
    <div class="receipt-total">
      <span>${escapeHtml(texts.totalUpper)}</span>
      <span>${escapeHtml(total.display)}</span>
    </div>
    <div class="receipt-divider"></div>
    <div class="receipt-footer">
      <p>${escapeHtml(texts.thankYou)}</p>
      <p>${escapeHtml(texts.autoGeneratedPrint)}</p>
      <p>${escapeHtml(receiptNumber)}</p>
    </div>
  </body>
</html>`;
}
